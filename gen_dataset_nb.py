"# ── Scan dataset ──────────────────────────────────────────────────────────────\n",
"records = []\n",
"for cls in sorted(os.listdir(DATASET_DIR)):\n",
"    cls_dir = os.path.join(DATASET_DIR, cls)\n",
"    if not os.path.isdir(cls_dir): continue\n",
"    for fname in os.listdir(cls_dir):\n",
"        ext = os.path.splitext(fname)[1].lower()\n",
"        if ext not in VALID_EXT: continue\n",
"        fpath = os.path.join(cls_dir, fname)\n",
"        sz    = os.path.getsize(fpath)\n",
"        try:\n",
"            with Image.open(fpath) as img:\n",
"                w, h, mode = img.width, img.height, img.mode\n",
"        except:\n",
"            w, h, mode = 0, 0, 'unknown'\n",
"        records.append({'class': cls, 'path': fpath, 'ext': ext,\n",
"                        'size_kb': sz/1024, 'width': w, 'height': h,\n",
"                        'mode': mode, 'aspect': round(w/h,2) if h else 0})\n",
"\n",
"df = pd.DataFrame(records)\n",
"classes = sorted(df['class'].unique())\n",
"NUM_CLASSES = len(classes)\n",
"print(f'Total images : {len(df)}')\n",
"print(f'Classes      : {NUM_CLASSES}')\n",
"print(f'Total size   : {df.size_kb.sum()/1024:.1f} MB')\n",
